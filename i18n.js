// ===== TILNI QO'LLASH =====
(function () {

  function detect() {
    try {
      var saved = localStorage.getItem('lang');
      if (I18N[saved]) return saved;
    } catch (e) {
      // localStorage taqiqlangan bo'lsa — e'tibor bermaymiz
    }

    var nav = (navigator.language || 'uz').toLowerCase();
    if (nav.indexOf('ru') === 0) return 'ru';
    if (nav.indexOf('en') === 0) return 'en';
    return 'uz';
  }

  function apply(lang, save) {
    var dict = I18N[lang] || I18N.uz;

    document.documentElement.setAttribute('lang', lang);
    document.title = dict.title;

    var meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute('content', dict.desc);

    // Oddiy matnlar
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (dict[key]) el.textContent = dict[key];
    });

    // aria-label va title atributlari
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-aria');
      if (dict[key]) {
        el.setAttribute('aria-label', dict[key]);
        if (el.hasAttribute('title')) el.setAttribute('title', dict[key]);
      }
    });

    // Tanlangan til tugmasini belgilash
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      var active = btn.getAttribute('data-lang') === lang;
      btn.classList.toggle('active', active);
      btn.setAttribute('aria-pressed', active ? 'true' : 'false');
    });

    if (save) {
      try {
        localStorage.setItem('lang', lang);
      } catch (e) {
        // Saqlab bo'lmasa ham til shu sahifada almashadi
      }
    }
  }

  function init() {
    apply(detect(), false);

    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.addEventListener('click', function () {
        apply(btn.getAttribute('data-lang'), true);
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
